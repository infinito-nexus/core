"""Run the Redis HA start-up wrapper against stub redis-cli/redis-server
binaries and check which role the instance starts in, and that the writable
main config keeps the include as the owner of every setting it declares."""

import os
import stat
import subprocess
import tempfile
import unittest
from pathlib import Path

from utils import PROJECT_ROOT

SCRIPT = PROJECT_ROOT / "roles" / "svc-db-redis" / "files" / "shell" / "ha_start.sh"

FAKE_CLI = """#!/bin/sh
[ "$REDISCLI_AUTH" = "sentinel-pw" ] || exit 1
while [ $# -gt 0 ]; do
  case "$1" in
    -h) host="$2"; shift 2 ;;
    *) shift ;;
  esac
done
[ -f "$FAKE_DIR/answers/$host" ] || exit 1
cat "$FAKE_DIR/answers/$host"
"""

FAKE_SERVER = """#!/bin/sh
printf '%s\\n' "$@" > "$FAKE_DIR/argv"
"""


def _read(path):
    return path.read_text(
        encoding="utf-8"
    )  # nocheck: cache-read  tempdir file the script under test rewrites


class HaStartTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.base = Path(self.tmp.name)
        self.bin = self.base / "bin"
        self.bin.mkdir()
        (self.base / "answers").mkdir()
        for name, body in (("redis-cli", FAKE_CLI), ("redis-server", FAKE_SERVER)):
            path = self.bin / name
            path.write_text(body, encoding="utf-8")
            path.chmod(path.stat().st_mode | stat.S_IXUSR)
        self.include = self.base / "infinito.conf"
        self.include.write_text(
            "# owned\nuser default on >pw ~* &* +@all\nmaxmemory 100mb\n",
            encoding="utf-8",
        )
        self.conf = self.base / "redis.conf"
        self.sentinel_password = self.base / "sentinel.pass"
        self.sentinel_password.write_text("sentinel-pw", encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def _sentinel_says(self, sentinel, master):
        (self.base / "answers" / sentinel).write_text(
            f"{master}\n6379\n", encoding="utf-8"
        )

    def _run(self, self_name="redis-b"):
        env = os.environ.copy()
        env.update(
            {
                "PATH": f"{self.bin}:{env['PATH']}",
                "FAKE_DIR": str(self.base),
                "REDIS_HA_SELF": self_name,
                "REDIS_HA_BOOTSTRAP": "redis-a",
                "REDIS_HA_MASTER_NAME": "redis",
                "REDIS_HA_SENTINELS": "s-a s-b s-c",
                "REDIS_HA_INCLUDE": str(self.include),
                "REDIS_HA_CONF": str(self.conf),
                "REDIS_HA_SENTINEL_PASSWORD_FILE": str(self.sentinel_password),
                "REDIS_HA_PORT": "6379",
                "REDIS_HA_SENTINEL_PORT": "26379",
            }
        )
        subprocess.run(["sh", str(SCRIPT)], env=env, check=True)
        return _read(self.base / "argv").split("\n")[:-1]

    def _replicaof(self, argv):
        if "--replicaof" not in argv:
            return None
        return argv[argv.index("--replicaof") + 1 :]

    def test_starts_as_replica_of_the_master_sentinels_report(self):
        self._sentinel_says("s-a", "redis-c")
        self._sentinel_says("s-b", "redis-c")
        self.assertEqual(self._replicaof(self._run()), ["redis-c", "6379"])

    def test_starts_as_master_when_sentinels_name_itself(self):
        self.conf.write_text("include x\nreplicaof redis-a 6379\n", encoding="utf-8")
        self._sentinel_says("s-a", "redis-b")
        self.assertEqual(self._replicaof(self._run()), ["no", "one"])

    def test_majority_of_answers_wins_over_a_stale_sentinel(self):
        self._sentinel_says("s-a", "redis-a")
        self._sentinel_says("s-b", "redis-c")
        self._sentinel_says("s-c", "redis-c")
        self.assertEqual(self._replicaof(self._run()), ["redis-c", "6379"])

    def test_no_sentinel_answer_keeps_the_config_file_role(self):
        argv = self._run()
        self.assertIsNone(self._replicaof(argv))
        self.assertIn("replicaof redis-a 6379", _read(self.conf))

    def test_fresh_bootstrap_instance_seeds_no_replicaof(self):
        self._run(self_name="redis-a")
        self.assertEqual(_read(self.conf), f"include {self.include}\n")

    def test_seeded_config_is_kept_but_include_owned_lines_are_dropped(self):
        self.conf.write_text(
            f"include {self.include}\nreplicaof redis-c 6379\n"
            "# Generated by CONFIG REWRITE\nuser default on >old ~* +@all\n"
            "maxmemory 1mb\nsave 3600 1\n",
            encoding="utf-8",
        )
        self._run()
        self.assertEqual(
            _read(self.conf).splitlines(),
            [
                f"include {self.include}",
                "replicaof redis-c 6379",
                "# Generated by CONFIG REWRITE",
                "save 3600 1",
            ],
        )

    def test_announces_its_own_service_name(self):
        argv = self._run()
        self.assertEqual(argv[0], str(self.conf))
        self.assertEqual(argv[argv.index("--replica-announce-ip") + 1], "redis-b")


if __name__ == "__main__":
    unittest.main()
