def code(iso: str) -> str:
    """Return the FLORES-200 code NLLB knows this ISO 639-1 language by.

    Args:
        iso: an ISO 639-1 code as ``meta/languages.yml`` keys it.

    Raises:
        ValueError: NLLB-200 ships no code for this language.
    """
    flores = ISO_TO_FLORES.get(iso)
    if flores is None:
        raise ValueError(f"NLLB-200 serves no FLORES-200 code for {iso!r}")
    return flores


@lru_cache(maxsize=1)
def pairs() -> frozenset[tuple[str, str]]:
    """Every ISO 639-1 pair NLLB-200 can render, as ``{(source, target)}``.

    NLLB is multilingual in both directions, so the catalogue is the product
    of the served codes minus the identity pairs, not a list of trained
    directions.
    """
    return frozenset(
        (source, target)
        for source in ISO_TO_FLORES
        for target in ISO_TO_FLORES
        if source != target
    )
