"""The FLORES-200 codes NLLB-200 speaks, and what they are in ISO 639-1.

NLLB names a language by a FLORES-200 code: an ISO 639-3 subtag joined to an
ISO 15924 script, ``deu_Latn`` and ``bel_Cyrl`` and ``amh_Ethi``. This
repository keys every language by its ISO 639-1 code in ``meta/languages.yml``,
so one of the two halves of that correspondence has to be written down.

Only the script half is derivable, and it is derived: a language writes its own
endonym in its own script, which is what ``utils.i18n.languages`` already reads
to tell a Latin table entry from a non-Latin one, and the unit test applies the
same reading to assert that every script suffix here agrees with the endonym.
The subtag half cannot be derived from anything this repository holds. It is
not even the plain ISO 639-3 of the 639-1 code: where the 639-1 code names a
macrolanguage, NLLB ships one individual variety of it and no other, so ``ar``
is ``arb_Arab`` and not ``ara``, ``fa`` is ``pes_Arab``, ``ms`` is ``zsm_Latn``,
``mn`` is ``khk_Cyrl``, ``sq`` is ``als_Latn``. That is stated once, here, and
the test holds it to :data:`SERVED` so a wrong subtag cannot reach the router.

``no`` and ``nb`` are the one pair that lands on the same FLORES code. The
table carries the Norwegian macrolanguage and Bokmål as separate catalogs,
while NLLB ships ``nob_Latn`` and ``nno_Latn`` and nothing for ``nor``, so
``Norsk`` is rendered as the written standard it names in practice.

:data:`UNSERVED` is the honest ceiling: the ISO codes of ``meta/languages.yml``
NLLB-200 has no code for at all. The test asserts it is exactly the complement
of :data:`ISO_TO_FLORES`, so a language can never be silently dropped from
either side.
"""

